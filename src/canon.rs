pub fn find(input: &str) -> Option<&'static Book> {
    let normalise = |s: &str| {
        s.to_ascii_lowercase()
            .chars()
            .filter(|c| c.is_ascii_alphanumeric())
            .collect::<String>()
    };
    let mut key = normalise(input);
    if key == "songofsongs" {
        key = "songofsolomon".into();
    }
    BOOKS.iter().find(|b| {
        normalise(b.title) == key || normalise(b.slug) == key || b.number.to_string() == key
    })
}
